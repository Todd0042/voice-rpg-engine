def ensure_pose_images(out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for name, pts in SKELETONS.items():
        p = out_dir / f"pose_{name}.png"
        if not p.is_file():
            im = Image.new("RGB", (768, 1024), (0, 0, 0))
            dr = ImageDraw.Draw(im)
            for a, b, col in LIMBS:
                if a in pts and b in pts:
                    dr.line([pts[a], pts[b]], fill=col, width=14)
            for _, (x, y) in pts.items():
                dr.ellipse([x - 10, y - 10, x + 10, y + 10], fill=(255, 255, 255))
            im.save(p)
        paths[name] = p
    return paths
